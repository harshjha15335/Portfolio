const at = (repo: Repo, path: string, label: string, project?: string): Where => {
  const [name, commit] = C[repo];
  return { label, href: `https://github.com/${name}/${path.endsWith('/') ? 'tree' : 'blob'}/${commit}/${path.replace(/\/$/, '')}`, project };
};
